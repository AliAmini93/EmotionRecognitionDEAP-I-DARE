def main() -> int:
    args = parse_args()
    t0 = time.perf_counter()

    args.out_npy.parent.mkdir(parents=True, exist_ok=True)
    args.out_index.parent.mkdir(parents=True, exist_ok=True)
    args.out_md.parent.mkdir(parents=True, exist_ok=True)
    args.out_json.parent.mkdir(parents=True, exist_ok=True)

    subject_files = sorted(args.deap_dir.glob("s*.dat"))
    if args.limit_subjects is not None:
        subject_files = subject_files[: args.limit_subjects]

    issues: list[str] = []
    warnings: list[str] = []

    if not subject_files:
        issues.append(f"No DEAP .dat files found in {args.deap_dir}")

    total_rows = len(subject_files) * TRIALS_PER_SUBJECT * WINDOWS_PER_TRIAL
    cache = open_memmap(
        args.out_npy,
        mode="w+",
        dtype="float32",
        shape=(total_rows, EEG_CHANNELS, WINDOW_SAMPLES),
    )

    rows: list[dict[str, Any]] = []
    baseline_mean_global_values: list[float] = []
    baseline_mean_abs_values: list[float] = []
    corrected_mean_before_zscore_values: list[float] = []
    corrected_std_before_zscore_values: list[float] = []
    window_mean_after_zscore_values: list[float] = []
    window_std_after_zscore_values: list[float] = []

    cache_row = 0

    print("Building DEAP EEG cache")
    print(f"DEAP dir: {args.deap_dir}")
    print(f"subject files: {len(subject_files)}")
    print(f"output: {args.out_npy}")

    for file_i, path in enumerate(subject_files, start=1):
        sid = subject_id_from_file(path)
        print(f"[{file_i:03d}/{len(subject_files):03d}] {path.name}")

        try:
            obj = load_deap_dat(path)
        except Exception as exc:
            issues.append(f"{path.name}: failed to load: {exc!r}")
            continue

        data = obj.get("data")
        labels = obj.get("labels")

        if not isinstance(data, np.ndarray):
            issues.append(f"{path.name}: data is not ndarray")
            continue
        if not isinstance(labels, np.ndarray):
            issues.append(f"{path.name}: labels is not ndarray")
            continue

        if tuple(data.shape) != (TRIALS_PER_SUBJECT, ALL_CHANNELS, SAMPLES_TOTAL):
            issues.append(f"{path.name}: unexpected data shape {list(data.shape)}")
            continue
        if tuple(labels.shape) != (TRIALS_PER_SUBJECT, len(LABEL_COLUMNS)):
            issues.append(f"{path.name}: unexpected labels shape {list(labels.shape)}")
            continue

        if not np.isfinite(data).all():
            issues.append(f"{path.name}: data contains NaN/Inf")
            continue
        if not np.isfinite(labels).all():
            issues.append(f"{path.name}: labels contains NaN/Inf")
            continue

        for trial_i in range(TRIALS_PER_SUBJECT):
            eeg = data[trial_i, :EEG_CHANNELS, :].astype(np.float32, copy=False)
            baseline = eeg[:, :BASELINE_SAMPLES]
            stimulus = eeg[:, BASELINE_SAMPLES:]

            if stimulus.shape != (EEG_CHANNELS, STIMULUS_SAMPLES):
                issues.append(f"{path.name} trial {trial_i}: bad stimulus shape {list(stimulus.shape)}")
                continue

            baseline_mean = baseline.mean(axis=1, keepdims=True)
            baseline_mean_global = float(baseline_mean.mean())
            baseline_mean_abs = float(np.abs(baseline_mean).mean())

            if args.no_baseline_correction:
                corrected = stimulus.copy()
                baseline_correction = "none"
            else:
                corrected = stimulus - baseline_mean
                baseline_correction = "subtract_deap_3s_baseline_per_channel_mean_then_window_global_zscore"

            corrected_mean = float(corrected.mean())
            corrected_std = float(corrected.std())

            baseline_mean_global_values.append(baseline_mean_global)
            baseline_mean_abs_values.append(baseline_mean_abs)
            corrected_mean_before_zscore_values.append(corrected_mean)
            corrected_std_before_zscore_values.append(corrected_std)

            scores = {
                "valence_score": float(labels[trial_i, 0]),
                "arousal_score": float(labels[trial_i, 1]),
                "dominance_score": float(labels[trial_i, 2]),
                "liking_score": float(labels[trial_i, 3]),
            }

            for window_i in range(WINDOWS_PER_TRIAL):
                start = window_i * WINDOW_SAMPLES
                end = start + WINDOW_SAMPLES
                window = corrected[:, start:end].astype(np.float32, copy=False)

                mean = float(window.mean())
                std = float(window.std())
                if std < 1e-8:
                    issues.append(f"{path.name} trial {trial_i} window {window_i}: near-zero std")
                    z = window - mean
                else:
                    z = (window - mean) / std

                cache[cache_row] = z.astype(np.float32, copy=False)

                window_mean_after_zscore_values.append(float(cache[cache_row].mean()))
                window_std_after_zscore_values.append(float(cache[cache_row].std()))

                row: dict[str, Any] = {
                    "cache_row": cache_row,
                    "subject_id": sid,
                    "subject_file": path.name,
                    "trial_id": trial_i + 1,
                    "trial_index_0based": trial_i,
                    "window_id": window_i + 1,
                    "window_index_0based": window_i,
                    "window_start_sample_128hz": int(BASELINE_SAMPLES + start),
                    "window_end_sample_128hz_exclusive": int(BASELINE_SAMPLES + end),
                    "baseline_correction": baseline_correction,
                    **scores,
                    "diag_baseline_mean_global": baseline_mean_global,
                    "diag_baseline_mean_abs_mean": baseline_mean_abs,
                    "diag_corrected_mean_before_zscore": corrected_mean,
                    "diag_corrected_std_before_zscore": corrected_std,
                }

                for task in ["valence", "arousal", "dominance", "liking"]:
                    score = row[f"{task}_score"]
                    for policy in ["discard_midpoint", "midpoint_as_low", "midpoint_as_high"]:
                        row[f"{task}_{policy}"] = bin_label(score, policy)

                rows.append(row)
                cache_row += 1

    cache.flush()

    index_df = pd.DataFrame(rows)
    index_df.to_csv(args.out_index, index=False)

    actual_shape = list(np.load(args.out_npy, mmap_mode="r").shape)
    status = "PASSED" if not issues and cache_row == total_rows else "CHECK_NEEDED"

    report = {
        "status": status,
        "config": {
            "source_fs": SOURCE_FS,
            "target_fs": TARGET_FS,
            "input": "DEAP data_preprocessed_python",
            "source_data_shape_per_subject": [TRIALS_PER_SUBJECT, ALL_CHANNELS, SAMPLES_TOTAL],
            "eeg_channels": EEG_CHANNELS,
            "baseline_samples": BASELINE_SAMPLES,
            "stimulus_samples": STIMULUS_SAMPLES,
            "window_samples": WINDOW_SAMPLES,
            "windows_per_trial": WINDOWS_PER_TRIAL,
            "baseline_correction": "none" if args.no_baseline_correction else "subtract 3s baseline per-channel mean",
            "normalization": "per-window global z-score",
            "limit_subjects": args.limit_subjects,
        },
        "inputs": {
            "deap_dir": str(args.deap_dir),
        },
        "outputs": {
            "eeg_cache_npy": str(args.out_npy),
            "cache_index_csv": str(args.out_index),
            "build_report_md": str(args.out_md),
            "build_report_json": str(args.out_json),
        },
        "counts": {
            "subject_files": len(subject_files),
            "expected_rows": total_rows,
            "extracted_rows": cache_row,
            "cache_index_rows": len(index_df),
        },
        "cache": {
            "shape": actual_shape,
            "dtype": "float32",
            "file_size": args.out_npy.stat().st_size if args.out_npy.exists() else None,
            "file_size_human": f"{args.out_npy.stat().st_size / (1024 * 1024):.2f} MB" if args.out_npy.exists() else None,
        },
        "diagnostics": {
            "baseline_mean_global": finite_summary(baseline_mean_global_values),
            "baseline_mean_abs_mean": finite_summary(baseline_mean_abs_values),
            "corrected_mean_before_zscore": finite_summary(corrected_mean_before_zscore_values),
            "corrected_std_before_zscore": finite_summary(corrected_std_before_zscore_values),
            "window_mean_after_zscore": finite_summary(window_mean_after_zscore_values),
            "window_std_after_zscore": finite_summary(window_std_after_zscore_values),
        },
        "label_counts": label_counts(index_df) if len(index_df) else {},
        "runtime": {
            "elapsed_sec": time.perf_counter() - t0,
        },
        "issues": issues,
        "warnings": warnings,
    }

    args.out_json.write_text(json.dumps(report, indent=2), encoding="utf-8")
    write_report_md(report, args.out_md)

    print(f"Wrote: {args.out_md}")
    print(f"Wrote: {args.out_json}")
    print(f"Status: {status}")
    print(f"Rows extracted: {cache_row} / {total_rows}")
    print(f"Cache size: {report['cache']['file_size_human']}")
    print(f"Elapsed: {report['runtime']['elapsed_sec']:.2f}s")
    print(f"Issues: {len(issues)}")
    print(f"Warnings: {len(warnings)}")

    return 0 if status == "PASSED" else 1


if __name__ == "__main__":
    raise SystemExit(main())
