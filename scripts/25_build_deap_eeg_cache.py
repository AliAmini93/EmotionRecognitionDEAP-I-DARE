#!/usr/bin/env python3
"""Build a NumPy EEG-window cache from DEAP preprocessed Python .dat files.

This script is smoke-first. It does not train a model.

DEAP preprocessed Python expected shape per subject:
- data:   [40, 40, 8064]
- labels: [40, 4]

Signal convention:
- first 32 channels are EEG
- first 384 samples are 3s baseline at 128Hz
- remaining 7680 samples are 60s stimulus at 128Hz
- stimulus is split into 12 non-overlapping 5s windows: 12 x 640

Preprocessing:
- subtract per-channel baseline mean from each 60s stimulus trial
- split into windows
- apply per-window global z-score
"""

from __future__ import annotations

import argparse
import json
import pickle
import time
from pathlib import Path
from typing import Any

import numpy as np
import pandas as pd
from numpy.lib.format import open_memmap


ROOT = Path(__file__).resolve().parents[1]

DEFAULT_DEAP_DIR = Path("/mnt/HDD/AliWorks/DEAP/data_preprocessed_python")
DEFAULT_OUT_NPY = ROOT / ".cache" / "deap_eeg_windows_32x640_float32_smoke.npy"
DEFAULT_OUT_INDEX = ROOT / ".cache" / "deap_eeg_cache_index_smoke.csv"
DEFAULT_OUT_MD = ROOT / "docs" / "deap_eeg_cache_build_smoke.md"
DEFAULT_OUT_JSON = ROOT / "docs" / "deap_eeg_cache_build_smoke.json"

SOURCE_FS = 128.0
TARGET_FS = 128.0
EEG_CHANNELS = 32
ALL_CHANNELS = 40
TRIALS_PER_SUBJECT = 40
SAMPLES_TOTAL = 8064
BASELINE_SAMPLES = 384
STIMULUS_SAMPLES = 7680
WINDOW_SAMPLES = 640
WINDOWS_PER_TRIAL = 12
LABEL_COLUMNS = ["valence", "arousal", "dominance", "liking"]


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--deap-dir", type=Path, default=DEFAULT_DEAP_DIR)
    parser.add_argument("--out-npy", type=Path, default=DEFAULT_OUT_NPY)
    parser.add_argument("--out-index", type=Path, default=DEFAULT_OUT_INDEX)
    parser.add_argument("--out-md", type=Path, default=DEFAULT_OUT_MD)
    parser.add_argument("--out-json", type=Path, default=DEFAULT_OUT_JSON)
    parser.add_argument(
        "--limit-subjects",
        type=int,
        default=None,
        help="Optional smoke limit on number of subject files.",
    )
    parser.add_argument(
        "--no-baseline-correction",
        action="store_true",
        help="Do not subtract the 3s baseline mean. Not recommended for main DEAP cache.",
    )
    return parser.parse_args()


def load_deap_dat(path: Path) -> dict[str, Any]:
    with path.open("rb") as f:
        return pickle.load(f, encoding="latin1")


def subject_id_from_file(path: Path) -> int:
    stem = path.stem
    if not (len(stem) == 3 and stem.startswith("s") and stem[1:].isdigit()):
        raise ValueError(f"Unexpected DEAP subject filename: {path.name}")
    return int(stem[1:])


def bin_label(score: float, policy: str) -> float:
    if policy == "discard_midpoint":
        if np.isclose(score, 5.0):
            return float("nan")
        return float(score > 5.0)
    if policy == "midpoint_as_low":
        return float(score > 5.0)
    if policy == "midpoint_as_high":
        return float(score >= 5.0)
    raise ValueError(f"Unknown label policy: {policy}")


def finite_summary(values: list[float]) -> dict[str, float | None]:
    arr = np.asarray(values, dtype=np.float64)
    arr = arr[np.isfinite(arr)]
    if arr.size == 0:
        return {"mean": None, "median": None, "min": None, "max": None}
    return {
        "mean": float(arr.mean()),
        "median": float(np.median(arr)),
        "min": float(arr.min()),
        "max": float(arr.max()),
    }


def label_counts(index_df: pd.DataFrame) -> dict[str, Any]:
    out: dict[str, Any] = {}
    for task in ["valence", "arousal", "dominance", "liking"]:
        out[task] = {}
        for policy in ["discard_midpoint", "midpoint_as_low", "midpoint_as_high"]:
            col = f"{task}_{policy}"
            s = index_df[col]
            counts = {
                "0": int((s == 0).sum()),
                "1": int((s == 1).sum()),
            }
            if policy == "discard_midpoint":
                counts["discard"] = int(s.isna().sum())
            out[task][policy] = counts
    return out


